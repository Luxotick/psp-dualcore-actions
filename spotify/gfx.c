void gfx_init(void)
{
    draw_buffer = VRAM_BASE;
    disp_buffer = VRAM_BASE + (BUF_WIDTH * GFX_HEIGHT);
    sceDisplaySetMode(0, GFX_WIDTH, GFX_HEIGHT);
    sceDisplaySetFrameBuf(disp_buffer, BUF_WIDTH, PSP_DISPLAY_PIXEL_FORMAT_8888,
                          PSP_DISPLAY_SETBUF_NEXTFRAME);
}

void gfx_clear(unsigned int color)
{
    for (int y = 0; y < GFX_HEIGHT; ++y) {
        unsigned int *row = draw_buffer + y * BUF_WIDTH;
        for (int x = 0; x < GFX_WIDTH; ++x) row[x] = color;
    }
}

void gfx_rect(int x, int y, int w, int h, unsigned int color)
{
    for (int j = 0; j < h; ++j) {
        int py = y + j;
        if (py < 0 || py >= GFX_HEIGHT) continue;
        for (int i = 0; i < w; ++i) {
            int px = x + i;
            if (px >= 0 && px < GFX_WIDTH) draw_buffer[py * BUF_WIDTH + px] = color;
        }
    }
}

static void glyph(unsigned char c, int x, int y, unsigned int color)
{
    if (c < 32 || c > 127) c = '?';
    const unsigned char *bitmap = font8x8[c - 32];
    for (int j = 0; j < 8; ++j) {
        int py = y + j;
        if (py < 0 || py >= GFX_HEIGHT) continue;
        for (int i = 0; i < 8; ++i) {
            int px = x + i;
            if ((bitmap[j] & (1 << i)) && px >= 0 && px < GFX_WIDTH)
                draw_buffer[py * BUF_WIDTH + px] = color;
        }
    }
}

/* Folds one UTF-8 sequence to a printable ASCII byte; returns bytes used. */
static int fold_utf8(const unsigned char *s, unsigned char *out)
{
    if (s[0] < 0x80) { *out = s[0]; return 1; }
    unsigned int cp;
    int n;
    if ((s[0] & 0xE0) == 0xC0 && (s[1] & 0xC0) == 0x80) {
        cp = ((s[0] & 0x1Fu) << 6) | (s[1] & 0x3Fu); n = 2;
    } else if ((s[0] & 0xF0) == 0xE0 && (s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80) {
        cp = ((s[0] & 0x0Fu) << 12) | ((s[1] & 0x3Fu) << 6) | (s[2] & 0x3Fu); n = 3;
    } else {
        int k = 1;
        while (k < 4 && (s[k] & 0xC0) == 0x80) ++k;
        *out = '?';
        return k;
    }
    static const struct { unsigned short cp; char ascii; } map[] = {
        {0x011F, 'g'}, {0x011E, 'G'}, {0x015F, 's'}, {0x015E, 'S'}, {0x0131, 'i'},
        {0x0130, 'I'}, {0x00F6, 'o'}, {0x00D6, 'O'}, {0x00FC, 'u'}, {0x00DC, 'U'},
        {0x00E7, 'c'}, {0x00C7, 'C'}, {0x00E9, 'e'}, {0x00E8, 'e'}, {0x00EA, 'e'},
        {0x00C9, 'E'}, {0x00E1, 'a'}, {0x00E0, 'a'}, {0x00E2, 'a'}, {0x00E4, 'a'},
        {0x00C4, 'A'}, {0x00ED, 'i'}, {0x00F3, 'o'}, {0x00FA, 'u'}, {0x00F1, 'n'},
        {0x00DF, 's'}, {0x2019, '\''}, {0x2018, '\''}, {0x201C, '"'}, {0x201D, '"'},
        {0x2013, '-'}, {0x2014, '-'}, {0x2026, '.'}, {0x00A0, ' '},
    };
    *out = '?';
    for (size_t i = 0; i < sizeof map / sizeof map[0]; ++i)
        if (map[i].cp == cp) { *out = (unsigned char)map[i].ascii; break; }
    return n;
}

int gfx_text(const char *text, int x, int y, unsigned int color, int max_chars)
{
    const unsigned char *s = (const unsigned char *)text;
    int drawn = 0;
    while (*s && (max_chars <= 0 || drawn < max_chars)) {
        unsigned char c;
        s += fold_utf8(s, &c);
        if (max_chars > 0 && drawn == max_chars - 1 && *s) c = '~';  /* truncated */
        glyph(c, x + drawn * 8, y, color);
        ++drawn;
    }
    return drawn;
}

void gfx_text_big(const char *text, int x, int y, unsigned int color, int scale)
{
    for (int k = 0; text[k]; ++k) {
        unsigned char c = (unsigned char)text[k];
        if (c < 32 || c > 127) c = '?';
        const unsigned char *bitmap = font8x8[c - 32];
        for (int j = 0; j < 8; ++j)
            for (int i = 0; i < 8; ++i)
                if (bitmap[j] & (1 << i))
                    gfx_rect(x + (k * 8 + i) * scale, y + j * scale, scale, scale, color);
    }
}

void gfx_flip(void)
{
    unsigned int *tmp = draw_buffer;
    draw_buffer = disp_buffer;
    disp_buffer = tmp;
    sceDisplaySetFrameBuf(disp_buffer, BUF_WIDTH, PSP_DISPLAY_PIXEL_FORMAT_8888,
                          PSP_DISPLAY_SETBUF_NEXTFRAME);
}
